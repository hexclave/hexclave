import { afterEach, describe, expect, it, vi } from "vitest";
import { GET } from "./route";

describe("observability lab symbolicated bundle route", () => {
  afterEach(() => {
    vi.unstubAllEnvs();
  });

  it("serves javascript that registers the demo thrower", async () => {
    vi.stubEnv("NEXT_PUBLIC_HEXCLAVE_PROJECT_ID", "internal");
    const response = await GET();
    expect(response.status).toBe(200);
    expect(response.headers.get("content-type")).toContain("application/javascript");
    expect(response.headers.get("cache-control")).toBe("no-store");
    const body = await response.text();
    expect(body).toContain("__hexclaveDemoThrowSymbolicatedChargeError");
    expect(body).toContain("hexclave:debug-id-injection:start");
  });
});
