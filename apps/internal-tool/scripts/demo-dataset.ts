/**
 * Fixture content for `pnpm seed:demo` (see seed-demo-data.ts).
 *
 * Pure data — no I/O, no env, no network — so the shape of the demo corpus can
 * be reviewed and edited without reading the transport around it. Everything
 * here is invented; it is written to look like real ask_hexclave traffic so the
 * grids, detail panels, and charts have something representative to render.
 *
 * Coverage is deliberate rather than random: between them these rows hit every
 * `qaState` bucket the module's page procedure accepts (pending, review-failed,
 * error, pass, warn, fail, feature-request) and every `humanReviewState`
 * (required, reviewed, not-reviewed), so the filter UI has a non-empty result
 * for each option.
 */

export type DemoToolCall = {
  toolName: string,
  toolCallId: string,
  args: unknown,
  result: unknown,
};

export type DemoQaFlag = {
  type: string,
  severity: "low" | "medium" | "high" | "critical",
  explanation: string,
  /** Only the feature-request flag carries a summary; see lib/feature-request-flag.ts. */
  summary?: string,
};

/** One step of the QA reviewer's own agent loop, as stored in qaConversationJson. */
export type DemoReviewStep = {
  step: number,
  text?: string,
  toolCalls?: Array<{ toolName: string, toolCallId: string, args: unknown }>,
  toolResults?: Array<{ toolName: string, toolCallId: string, result: unknown }>,
};

export type DemoReview = {
  needsHumanReview: boolean,
  answerCorrect: boolean,
  answerRelevant: boolean,
  flags: DemoQaFlag[],
  improvementSuggestions: string,
  overallScore: number,
  reviewModelId: string,
  conversation: DemoReviewStep[],
  /**
   * Set instead of the fields above when the review itself blew up. Puts the
   * row in the `error` QA state.
   */
  reviewErrorMessage?: string,
};

export type DemoMcpCall = {
  /** Stable per-row suffix; the correlation id is derived from it so re-seeding is deterministic. */
  slug: string,
  conversationSlug: string,
  toolName: string,
  reason: string,
  userPrompt: string,
  context: string,
  user: string,
  project: string,
  question: string,
  response: string,
  stepCount: number,
  durationMs: number,
  modelId: string,
  innerToolCalls: DemoToolCall[],
  /** An upstream failure while answering; puts the row in the `hasError` bucket. */
  errorMessage?: string,
  review?: DemoReview,
  humanReviewed?: boolean,
  /** Curate the call into the knowledge base, optionally publishing it. */
  publishToQa?: { question: string, answer: string, publish: boolean },
};

