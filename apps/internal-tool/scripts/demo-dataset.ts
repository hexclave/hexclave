function docsSearch(id: string, query: string, titles: string[]): DemoToolCall {
  return {
    toolName: "search_docs",
    toolCallId: `call_${id}`,
    args: { query },
    result: titles.map((title, i) => ({
      title,
      url: `https://docs.hexclave.com/${title.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "")}`,
      score: Number((0.94 - i * 0.07).toFixed(2)),
    })),
  };
}

function deepwikiReview(id: string, question: string, finding: string, verdict: string): DemoReviewStep[] {
  return [
    {
      step: 1,
      toolCalls: [{ toolName: "ask_question", toolCallId: `rev_${id}`, args: { repoName: "hexclave/hexclave", question } }],
      toolResults: [{ toolName: "ask_question", toolCallId: `rev_${id}`, result: finding }],
    },
    { step: 2, text: verdict },
  ];
}

